/**
 * Build-time only: the models the installed WebLLM runs, from its
 * `prebuiltAppConfig`, written to src/ai/engineModels.ts so the page can rank
 * models without loading WebLLM (several MB). Run again after upgrading
 * @mlc-ai/web-llm: src/ai/models.test.ts fails until then.
 */
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { ModelType, prebuiltAppConfig } from "@mlc-ai/web-llm";

export const OUT = resolve(import.meta.dir, "../src/ai/engineModels.ts");

/** The source of src/ai/engineModels.ts for the installed WebLLM. */
export function engineModelsSource(): string {
  const rows = prebuiltAppConfig.model_list
    .filter((m) => (m.model_type ?? ModelType.LLM) === ModelType.LLM)
    .map((m) => {
      const id = JSON.stringify(m.model_id);
      const vramMb = Math.ceil(m.vram_required_MB ?? 0);
      const shaderF16 = m.required_features?.includes("shader-f16") ?? false;
      const lowResource = m.low_resource_required ?? false;
      const contextWindow = m.overrides?.context_window_size ?? 4096;
      return `  [${id}, ${vramMb}, ${shaderF16}, ${lowResource}, ${contextWindow}],`;
    });
  return `// Generated by scripts/engine-models.ts from @mlc-ai/web-llm's prebuiltAppConfig: do not edit.

export interface EngineModel {
  id: string;
  /** GPU memory WebLLM says the model needs. */
  vramMb: number;
  /** Needs fp16 compute (\`shader-f16\`). */
  shaderF16: boolean;
  /** Loads on adapters that bind less than 1 GiB per storage buffer. */
  lowResource: boolean;
  /** Tokens of context the prebuilt library is compiled for. */
  contextWindow: number;
}

/** id, vramMb, shaderF16, lowResource, contextWindow. */
const ROWS: readonly (readonly [string, number, boolean, boolean, number])[] = [
${rows.join("\n")}
];

/** Language models of the installed WebLLM. */
export const ENGINE_MODELS: readonly EngineModel[] = ROWS.map(
  ([id, vramMb, shaderF16, lowResource, contextWindow]) => ({
    id,
    vramMb,
    shaderF16,
    lowResource,
    contextWindow,
  }),
);
`;
}

if (import.meta.main) {
  await writeFile(OUT, engineModelsSource());
  console.log(`engine models written to ${OUT}`);
}
